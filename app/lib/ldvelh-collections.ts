export function getAllCollections(): LDVELHCollection[] {
  return LDVELH_COLLECTIONS;
}

export function getCollectionById(id: string): LDVELHCollection | undefined {
  return LDVELH_COLLECTIONS.find((c) => c.id === id);
}

export function getAllBooks(): LDVELHBook[] {
  return LDVELH_COLLECTIONS.flatMap((c) => c.books);
}

export function getBookById(id: string): LDVELHBook | undefined {
  return getAllBooks().find((b) => b.id === id);
}

export function getPlayableBooks(): LDVELHBook[] {
  return getAllBooks().filter((b) => b.isPlayable);
}

export function searchBooks(query: string, collectionId?: string): LDVELHBook[] {
  const normalized = query.toLowerCase().trim();
  let pool = getAllBooks();
  if (collectionId && collectionId !== "all") {
    pool = pool.filter((b) => b.collectionId === collectionId);
  }
  if (!normalized) return pool;
  return pool.filter(
    (b) =>
      b.titre.toLowerCase().includes(normalized) ||
      b.resume.toLowerCase().includes(normalized) ||
      b.collectionName.toLowerCase().includes(normalized) ||
      b.author.toLowerCase().includes(normalized)
  );
}
